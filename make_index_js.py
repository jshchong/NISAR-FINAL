#!/usr/bin/env python3
"""Regenerate layers/index.js from layers/index.json.

index.js defines window.NISAR_LAYERS so index.html still works when opened
via file:// (where fetch() of index.json is blocked). Re-run after adding
regions:  python3 make_index_js.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "layers", "index.json")
DST = os.path.join(HERE, "layers", "index.js")

with open(SRC, encoding="utf-8") as f:
    layers = json.load(f)
if not isinstance(layers, list):
    raise SystemExit("layers/index.json must contain a JSON array")

body = json.dumps(layers, indent=1, ensure_ascii=False)
tmp = DST + ".tmp"
with open(tmp, "w", encoding="utf-8") as f:
    f.write("// Generated by make_index_js.py from layers/index.json - do not edit.\n")
    f.write("window.NISAR_LAYERS = " + body + ";\n")
os.replace(tmp, DST)
print(f"wrote {DST} ({len(layers)} regions)")
